# 按概念聚合
def get_stocks_by_concept(concept_keyword=None):
    """获取某个概念下的股票列表"""
    result = {}
    for code, info in FIFTEEN_FIVE_STOCKS.items():
        if concept_keyword is None:
            result[code] = info
        elif any(concept_keyword.lower() in c.lower() for c in info['concepts']):
            result[code] = info
    return result

def get_all_concepts():
    """获取所有概念标签列表"""
    concepts = set()
    for info in FIFTEEN_FIVE_STOCKS.values():
        for c in info['concepts']:
            concepts.add(c)
    return sorted(concepts)

def get_multi_concept_stocks(min_concepts=3):
    """获取覆盖多个概念的股票（概念共振最强的）"""
    result = []
    for code, info in FIFTEEN_FIVE_STOCKS.items():
        if len(info['concepts']) >= min_concepts:
            result.append((code, info, len(info['concepts'])))
    result.sort(key=lambda x: x[2], reverse=True)
    return result

